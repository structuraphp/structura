<?php

declare(strict_types=1);

namespace StructuraPhp\Structura\Tests\Unit\Services;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use StructuraPhp\Structura\Asserts\ToHaveMethod;
use StructuraPhp\Structura\Asserts\ToNotDependOn;
use StructuraPhp\Structura\Services\BaselineGenerator;
use StructuraPhp\Structura\Services\BaselineService;
use StructuraPhp\Structura\Tests\Helper\Sandbox;
use StructuraPhp\Structura\ValueObjects\AnalyseTestValueObject;
use StructuraPhp\Structura\ValueObjects\AnalyseValueObject;
use StructuraPhp\Structura\ValueObjects\AssertValueObject;
use StructuraPhp\Structura\ValueObjects\SourceTestValueObject;
use StructuraPhp\Structura\ValueObjects\ViolationValueObject;

#[CoversClass(BaselineGenerator::class)]
final class BaselineGeneratorTest extends TestCase
{
    use Sandbox;

    private const BASE = '/home/a/project';

    protected function setUp(): void
    {
        $this->enterSandbox();
    }

    protected function tearDown(): void
    {
        $this->leaveSandbox();
    }

    public function testGeneratesSortedEntries(): void
    {
        $content = BaselineGenerator::generate(
            $this->analyse([
                'testLegacy' => [
                    'to not depend on' => [
                        $this->violation('depends on <fire>Legacy\Mailer</fire>', '/src/A.php'),
                    ],
                ],
                'testDependencies' => [
                    'to not depend on' => [
                        $this->violation('depends on <fire>Legacy\Zip</fire>', '/src/B.php'),
                        $this->violation('depends on <fire>Legacy\Mailer</fire>', '/src/B.php'),
                        $this->violation('depends on <fire>Legacy\Mailer</fire>', '/src/B.php'),
                        $this->violation('depends on <fire>Legacy\Mailer</fire>', '/src/A.php'),
                    ],
                    'to have method' => [
                        $this->violation('Resource <promote>Foo</promote> must have method <promote>__construct</promote>', '/src/A.php', ToHaveMethod::class),
                    ],
                ],
            ]),
            self::BASE,
        );

        self::assertSame(
            <<<'PHP'
            <?php

            declare(strict_types=1);

            // Generated by `structura analyze --generate-baseline`.
            return [
                'Tests\\TestAssert::testDependencies' => [
                    'src/A.php' => [
                        'ToHaveMethod' => [
                            'Resource Foo must have method __construct',
                        ],
                        'ToNotDependOn' => [
                            'Legacy\\Mailer',
                        ],
                    ],
                    'src/B.php' => [
                        'ToNotDependOn' => [
                            'Legacy\\Mailer',
                            'Legacy\\Zip',
                        ],
                    ],
                ],
                'Tests\\TestAssert::testLegacy' => [
                    'src/A.php' => [
                        'ToNotDependOn' => [
                            'Legacy\\Mailer',
                        ],
                    ],
                ],
            ];

            PHP,
            $content,
        );
    }

    public function testSkipsRawSources(): void
    {
        $content = BaselineGenerator::generate(
            $this->analyse(['testRaw' => ['rule' => [new ViolationValueObject('depends on <fire>Raw</fire>', ToNotDependOn::class, 1, 'tmp/run_0.php', '')]]]),
            self::BASE,
        );

        self::assertStringNotContainsString('Raw', $content);
        self::assertStringNotContainsString('tmp/run_0.php', $content);
    }

    public function testSkipsRulesWrittenAsAnonymousClasses(): void
    {
        $anonymous = new ViolationValueObject(
            'depends on <fire>Legacy\Mailer</fire>',
            "class@anonymous\0/home/a/project/tests/Rule.php:5$0",
            1,
            self::BASE . '/src/A.php',
            '',
        );

        file_put_contents('baseline.php', BaselineGenerator::generate($this->analyse(['testAnonymous' => ['rule' => [$anonymous]]]), self::BASE));

        self::assertSame([], BaselineService::fromFile('baseline.php', self::BASE)->getStaleWarnings());
    }

    public function testGeneratedFileRoundTrips(): void
    {
        $violations = [
            $this->violation("depends on <fire>App\\O'Reilly\\Mailer</fire>", '/src/A.php'),
            $this->violation('depends on <fire>Legacy\Mailer</fire>', '/src/A.php'),
            $this->violation('depends on <fire>Legacy\</fire>', '/src/A.php'),
            $this->violation('depends on <fire>a\\\b</fire>', '/src/A.php'),
            $this->violation("depends on <fire>it\\'s</fire>", '/src/A.php'),
            $this->violation('<fire>X</fire>', '/src/A.php', 'App\Rules\ToNotDependOn'),
            $this->violation('<fire>M</fire>', '/src/A.php', ToHaveMethod::class),
        ];

        file_put_contents('baseline.php', BaselineGenerator::generate($this->analyse(['testDependencies' => ['rule' => $violations]]), self::BASE));
        $service = BaselineService::fromFile('baseline.php', self::BASE);

        foreach ($violations as $violation) {
            self::assertTrue($service->isTolerated($this->source('testDependencies'), $violation));
        }

        self::assertSame([], $service->getStaleWarnings());
    }

    public function testEmptyResultGeneratesEmptyArray(): void
    {
        self::assertStringEndsWith("return [];\n", BaselineGenerator::generate($this->analyse([]), self::BASE));
    }

    /**
     * @param array<string, array<string, array<int, ViolationValueObject>>> $violationsByTest test method => rule => violations
     */
    private function analyse(array $violationsByTest): AnalyseValueObject
    {
        $tests = [];
        foreach ($violationsByTest as $method => $violations) {
            $tests[] = new AnalyseTestValueObject(
                source: $this->source($method),
                ruleValueObjects: [],
                assertValueObject: new AssertValueObject(violations: $violations),
            );
        }

        return new AnalyseValueObject(
            timeStart: 0,
            countPass: 0,
            countViolation: \count($violationsByTest),
            countWarning: 0,
            countNotice: 0,
            analyseTestValueObjects: $tests,
        );
    }

    private function source(string $method): SourceTestValueObject
    {
        return new SourceTestValueObject('Tests\TestAssert', 'Asserts', $method, 0, '');
    }

    private function violation(string $message, string $path, string $rule = ToNotDependOn::class): ViolationValueObject
    {
        return new ViolationValueObject($message, $rule, 1, self::BASE . $path, '');
    }
}
