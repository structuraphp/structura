<?php

declare(strict_types=1);

namespace StructuraPhp\Structura\Services;

use StructuraPhp\Structura\ValueObjects\AnalyseValueObject;
use StructuraPhp\Structura\ValueObjects\BaselineEntryValueObject;

/**
 * Writes test => path => rule => identifiers, sorted at every level to keep review diffs small.
 */
final readonly class BaselineGenerator
{
    private const INDENT = '    ';

    public static function generate(AnalyseValueObject $result, string $baseDirectory): string
    {
        $tree = [];
        foreach ($result->analyseTestValueObjects as $test) {
            foreach (array_merge(...array_values($test->assertValueObject->violations)) as $violation) {
                $entry = BaselineEntryValueObject::fromViolation($test->source, $violation, $baseDirectory);

                if ($entry instanceof BaselineEntryValueObject) {
                    $tree[$entry->test][$entry->path][$entry->rule][$entry->identifier] = $entry->identifier;
                }
            }
        }

        return \sprintf(
            <<<'PHP'
                <?php

                declare(strict_types=1);

                // Generated by `structura analyze --generate-baseline`.
                return %s;

                PHP,
            self::export($tree),
        );
    }

    /**
     * @param array<array-key, mixed> $values
     */
    private static function export(array $values, int $depth = 0): string
    {
        if ($values === []) {
            return '[]';
        }

        ksort($values);

        $indent = str_repeat(self::INDENT, $depth + 1);

        $lines = [];
        foreach ($values as $key => $value) {
            $lines[] = \is_array($value)
                ? \sprintf(
                    '%s%s => %s,',
                    $indent,
                    var_export($key, true),
                    self::export($value, $depth + 1),
                )
                : \sprintf('%s%s,', $indent, var_export($value, true));
        }

        return \sprintf(
            "[\n%s\n%s]",
            implode("\n", $lines),
            str_repeat(self::INDENT, $depth),
        );
    }
}
