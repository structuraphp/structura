<?php

declare(strict_types=1);

namespace StructuraPhp\Structura\Services;

use StructuraPhp\Structura\ValueObjects\AnalyseValueObject;
use StructuraPhp\Structura\ValueObjects\BaselineEntryValueObject;

/**
 * Writes the baseline file: path => rule => identifiers, sorted at every level
 * so that the file stays readable and its diffs stay small in code review.
 */
final readonly class BaselineGenerator
{
    public static function generate(AnalyseValueObject $result, string $baseDirectory): string
    {
        /** @var array<string, array<string, array<int, string>>> $entries */
        $entries = [];
        foreach ($result->getViolations() as $violations) {
            foreach ($violations as $violation) {
                $entry = BaselineEntryValueObject::fromViolation($violation, $baseDirectory);
                if ($entry instanceof BaselineEntryValueObject) {
                    $entries[$entry->path][$entry->rule][] = $entry->identifier;
                }
            }
        }

        ksort($entries);

        $lines = ['<?php', '', '// Generated by `structura analyze --generate-baseline`.', 'return ['];
        foreach ($entries as $path => $rules) {
            ksort($rules);

            $lines[] = \sprintf('    %s => [', var_export($path, true));
            foreach ($rules as $rule => $identifiers) {
                $identifiers = array_unique($identifiers);
                sort($identifiers);

                $lines[] = \sprintf('        \%s::class => [', $rule);
                foreach ($identifiers as $identifier) {
                    $lines[] = \sprintf('            %s,', var_export($identifier, true));
                }

                $lines[] = '        ],';
            }

            $lines[] = '    ],';
        }

        $lines[] = '];';

        return implode("\n", $lines) . "\n";
    }
}
